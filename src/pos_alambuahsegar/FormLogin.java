    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
    String username = txtUsername.getText().trim();
    String password = new String(txtPassword.getPassword()).trim();
    
    // Validasi jika kolom kosong
    if (username.isEmpty() || password.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, 
            "ID Admin dan PIN Kasir tidak boleh kosong!", 
            ",Peringatan", 
            javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }
    
    try {
        // Memanggil koneksi database
        java.sql.Connection conn = com.alambuahsegar.config.DatabaseConnection.getConnection();
        
        // Mengecek data ke tabel 'pengguna'
        String sql = "SELECT * FROM pengguna WHERE username = ? AND password = ?";
        java.sql.PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, username);
        pst.setString(2, password);
        
        java.sql.ResultSet rs = pst.executeQuery();
        
       if (rs.next()) {
            // --- TAMBAHAN: Cek apakah akun berstatus Nonaktif ---
            String status = rs.getString("status");
            if (status != null && status.equalsIgnoreCase("Nonaktif")) {
                javax.swing.JOptionPane.showMessageDialog(this, 
                    "Login Gagal! Akun Anda sudah nonaktif. Silakan hubungi Administrator.", 
                    "Akses Ditolak", 
                    javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }
            

            // --- TAMBAHAN: Update waktu terakhir login secara otomatis ---
            try {
                String updateSql = "UPDATE pengguna SET terakhir_login = NOW() WHERE id_pengguna = ?";
                java.sql.PreparedStatement updatePst = conn.prepareStatement(updateSql);
                updatePst.setInt(1, rs.getInt("id_pengguna"));
                updatePst.executeUpdate();
            } catch (Exception ex) {
                System.out.println("Gagal update waktu login: " + ex.getMessage());
            }
            

            // 1. Simpan data ke Session
            com.alambuahsegar.config.Session.id_pengguna = rs.getInt("id_pengguna");
            com.alambuahsegar.config.Session.username = rs.getString("username");
            com.alambuahsegar.config.Session.role = rs.getString("role");

            // 2. Pesan sukses login
            javax.swing.JOptionPane.showMessageDialog(this, "Login Berhasil! Selamat datang, " + username);
            
            String role = com.alambuahsegar.config.Session.role;
                
            if (role.equalsIgnoreCase("Admin")) {
                new FormDashboardAdmin().setVisible(true);
                this.dispose();
            } 
            else if (role.equalsIgnoreCase("Kasir")) {
                new FormDashboardKasir(); 
                new FormDashboardKasir().setVisible(true);
                this.dispose();
            } 
            else if (role.equalsIgnoreCase("Manager")) {
                new FormDashboardManager().setVisible(true);
                this.dispose();
            } 
            else {
                javax.swing.JOptionPane.showMessageDialog(this, "Role pengguna tidak dikenal!");
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "ID Admin atau PIN Kasir salah!", 
                "Error Login", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
        
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Terjadi kesalahan database: " + e.getMessage(), 
            "Database Error", 
            javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnLoginActionPerformed

