    private void tblStokMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblStokMouseClicked
    int baris = tblStok.getSelectedRow();
    int kolom = tblStok.getSelectedColumn();
    
    if (baris != -1) {
        // Mengisi form bawah sesuai urutan kolom tabel yang tepat:
        txtPilihProduk.setText(tblStok.getValueAt(baris, 1).toString()); // Nama Produk (Kolom 1)
        txtHargaDiskon.setText(tblStok.getValueAt(baris, 2).toString()); // Diskon (Kolom 2)
        txtHargaBuah.setText(tblStok.getValueAt(baris, 3).toString());   // Harga Buah (Kolom 3 - Menggantikan Tanggal)
        txtStokRak.setText(tblStok.getValueAt(baris, 4).toString());         // Stok Rak (Kolom 4)
        txtStokGudang.setText(tblStok.getValueAt(baris, 5).toString());   // Stok Gudang (Kolom 5)
        txtStokSistem.setText(tblStok.getValueAt(baris, 6).toString());   // Stok Sistem (Kolom 6)

        // Jika user mengklik pada kolom "AKSI" (Kolom index ke-8)
        if (kolom == 8) {
            String idProdukStr = tblStok.getValueAt(baris, 0).toString(); // Contoh: "PRD101"
            int idProduk = Integer.parseInt(idProdukStr.replace("PRD", "")) - 100;
            String namaProduk = tblStok.getValueAt(baris, 1).toString();
            
            // Opsi popup hanya menyisakan Hapus Produk dan Batal (Menu Edit sudah dihapus bersih)
            Object[] options = {"Hapus Produk", "Batal"};
            int pilihan = javax.swing.JOptionPane.showOptionDialog(this, 
                "Pilih aksi untuk produk: " + namaProduk, 
                "Menu Aksi Produk", 
                javax.swing.JOptionPane.DEFAULT_OPTION, 
                javax.swing.JOptionPane.QUESTION_MESSAGE, 
                null, options, options[1]);
        
            if (pilihan == 0) { // HAPUS
                int konfirmasi = javax.swing.JOptionPane.showConfirmDialog(this, 
                    "Yakin ingin menghapus produk " + namaProduk + "?", 
                    "Konfirmasi Hapus", 
                    javax.swing.JOptionPane.YES_NO_OPTION);
            
                if (konfirmasi == javax.swing.JOptionPane.YES_OPTION) {
                    try {
                        java.sql.Connection conn = (java.sql.Connection) com.alambuahsegar.config.DatabaseConnection.getConnection();
                        String sql = "DELETE FROM produk WHERE id_produk = ?";
                        java.sql.PreparedStatement pst = conn.prepareStatement(sql);
                        pst.setInt(1, idProduk);
                        pst.execute();
                        
                        javax.swing.JOptionPane.showMessageDialog(this, "Produk berhasil dihapus!");
                        tampilkanData();
                    } catch (Exception e) {
                        javax.swing.JOptionPane.showMessageDialog(this, "Gagal menghapus produk: " + e.getMessage());
                    }
                }
            }
        }
    }
    }//GEN-LAST:event_tblStokMouseClicked

