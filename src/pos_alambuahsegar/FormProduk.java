    private void btnExportExcelActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportExcelActionPerformed
    try {
    javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
fileChooser.setDialogTitle("Simpan Laporan Stok Produk ke Excel");
fileChooser.setSelectedFile(new java.io.File("Laporan_Stok_Produk_AlamBuahSegar.xls"));

int userSelection = fileChooser.showSaveDialog(this);

if (userSelection == javax.swing.JFileChooser.APPROVE_OPTION) {
    java.io.File fileToSave = fileChooser.getSelectedFile();
    String filePath = fileToSave.getAbsolutePath();
    if (!filePath.endsWith(".xls")) {
        filePath += ".xls";
    }
    
    java.io.BufferedWriter bufferedWriter = null;
    try {
        bufferedWriter = new java.io.BufferedWriter(new java.io.FileWriter(filePath));
        javax.swing.table.TableModel model = tblStok.getModel();
        
        StringBuilder html = new StringBuilder();
        html.append("<html>\n<head>\n<meta charset='UTF-8'>\n");
        html.append("<style>\n");
        html.append("body { font-family: Arial, sans-serif; }\n");
        html.append("h2, h3 { text-align: center; color: #000000; margin: 2px; }\n"); // Diubah jadi warna hitam
        html.append("p { text-align: center; color: #555; font-size: 11px; margin-bottom: 15px; }\n");
        html.append("table { border-collapse: collapse; width: 100%; margin-top: 10px; }\n");
        html.append("th { color: white; padding: 8px 12px; border: 1px solid #ddd; text-align: center; font-size: 12px; }\n");
        html.append("td { padding: 6px 10px; border: 1px solid #ddd; font-size: 11px; }\n");
        html.append("</style>\n</head>\n<body>\n");
        
        // Judul Laporan (Warna Hitam)
        html.append("<h2>TOKO ALAM BUAH SEGAR</h2>\n");
        html.append("<h3>Laporan Stok Produk & Inventaris</h3>\n");
        html.append("<p>Tanggal Cetak: ").append(new java.text.SimpleDateFormat("EEEE, dd MMM yyyy", new java.util.Locale("id", "ID")).format(new java.util.Date())).append("</p>\n");
        html.append("<br>\n");
        
        // Tabel HTML dengan header warna hijau
        html.append("<table>\n<thead>\n<tr bgcolor='#28a745'>\n");
        
        int colCount = model.getColumnCount();
        int maxCols = colCount;
        if (colCount > 0 && model.getColumnName(colCount - 1).equalsIgnoreCase("AKSI")) {
            maxCols = colCount - 1;
        }
        
        for (int i = 0; i < maxCols; i++) {
            html.append("<th>").append(model.getColumnName(i)).append("</th>\n");
        }
        html.append("</tr>\n</thead>\n<tbody>\n");
        
        // Tulis Data Baris Tabel
        for (int i = 0; i < model.getRowCount(); i++) {
            html.append("<tr>\n");
            for (int j = 0; j < maxCols; j++) {
                Object val = model.getValueAt(i, j);
                String valStr = (val == null) ? "" : val.toString();
                
                String align = "left";
                if (j == 0 || j >= maxCols - 1) align = "center";
                else if (j >= 2 && j <= 6) align = "right";
                
                html.append("<td align='").append(align).append("'>").append(valStr).append("</td>\n");
            }
            html.append("</tr>\n");
        }
        
        html.append("</tbody>\n</table>\n");
        html.append("</body>\n</html>");
        
        bufferedWriter.write(html.toString());
        bufferedWriter.flush();
        bufferedWriter.close();
        
        javax.swing.JOptionPane.showMessageDialog(this, "Laporan Stok Berhasil Diexport ke Excel dengan Rapi!\nLokasi: " + filePath);
        
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Gagal mengexport data: " + e.getMessage());
    } finally {
        try {
            if (bufferedWriter != null) bufferedWriter.close();
        } catch (java.io.IOException ex) {}
    }
}
    } catch (Exception ex) {
    javax.swing.JOptionPane.showMessageDialog(this, "Gagal export data: " + ex.getMessage());
    }
    }//GEN-LAST:event_btnExportExcelActionPerformed

