    // 2. Method Tampilkan Data ke Tabel
    public void tampilkanData() {
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel();
        model.addColumn("KODE");
        model.addColumn("NAMA PRODUK");
        model.addColumn("DISKON");
        model.addColumn("HARGA");
        model.addColumn("STOK RAK");
        model.addColumn("STOK GUDANG");
        model.addColumn("STOK SISTEM");
        model.addColumn("SATUAN");
        model.addColumn("AKSI");
        
        tblStok.setModel(model);
        
        try {
            java.sql.Connection conn = (java.sql.Connection) com.alambuahsegar.config.DatabaseConnection.getConnection();
            java.sql.Statement stm = conn.createStatement();
            java.sql.ResultSet res = stm.executeQuery("SELECT * FROM produk");
            
            while (res.next()) {
                String kodeFormat = "PRD" + (100 + res.getInt("id_produk"));
                
                model.addRow(new Object[]{
                    kodeFormat,
                    res.getString("nama_produk"),
                    (int) res.getDouble("harga_diskon"),
                    (int) res.getDouble("harga_jual"),
                    res.getInt("stok_di_rak"),
                    res.getInt("stok_di_gudang"),
                    res.getInt("total_stok_sistem"),
                    res.getString("satuan"),
                    "Hapus"
                });
            }
            
            tblStok.setRowHeight(30); 
            tblStok.setFont(new java.awt.Font("Segoe UI", java.awt.Font.PLAIN, 12));
            tblStok.getTableHeader().setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 11));
            tblStok.getTableHeader().setForeground(java.awt.Color.BLACK);
            
            tblStok.getColumnModel().getColumn(8).setCellRenderer(new javax.swing.table.DefaultTableCellRenderer() {
            @Override
            public java.awt.Component getTableCellRendererComponent(javax.swing.JTable table, Object value, boolean isSelected, boolean hasFocus, int row, int column) {
            java.awt.Component c = super.getTableCellRendererComponent(table, value, isSelected, hasFocus, row, column);
        
            if (value != null && value.toString().equalsIgnoreCase("Hapus")) {
            c.setForeground(java.awt.Color.RED);
            setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 12));
            } else {
            c.setForeground(table.getForeground());
            setFont(new java.awt.Font("Segoe UI", java.awt.Font.PLAIN, 12));
            }
        
            setHorizontalAlignment(javax.swing.JLabel.CENTER);
            return c;
        }
});
           
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal memuat data produk: " + e.getMessage());
        }
    }
                                   
                                   

