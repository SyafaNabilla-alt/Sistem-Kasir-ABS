    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
    try {
    java.sql.Connection conn = com.alambuahsegar.config.DatabaseConnection.getConnection();
    
    // Ambil nilai murni langsung dari kotak teks masing-masing tanpa penjumlahan otomatis
    int stokSistem = Integer.parseInt(txtStokSistem.getText());
    int stokRak = Integer.parseInt(txtStokRak.getText());
    int stokGudang = Integer.parseInt(txtStokGudang.getText());
    double hargaDiskon = Double.parseDouble(txtHargaDiskon.getText());
    
    // Ambil nama produk dari kotak teks "Pilih Produk" yang baru saja kita beri nama txtPilihProduk
    String namaProduk = txtPilihProduk.getText();

    // Query update ke database berdasarkan nama_produk
    String sql = "UPDATE produk SET total_stok_sistem = ?, stok_di_rak = ?, stok_di_gudang = ?, harga_diskon = ? WHERE nama_produk = ?";
    java.sql.PreparedStatement pstmt = conn.prepareStatement(sql);
    pstmt.setInt(1, stokSistem);
    pstmt.setInt(2, stokRak);
    pstmt.setInt(3, stokGudang);
    pstmt.setDouble(4, hargaDiskon);
    pstmt.setString(5, namaProduk);

    pstmt.executeUpdate();
    javax.swing.JOptionPane.showMessageDialog(this, "Data stok berhasil diperbarui!");
    
    // Refresh tabel (ganti loadDataProduk dengan nama method refresh tabel aslimu jika berbeda, misal loadData() atau tampilTabel())
    tampilkanData(); 

} catch (Exception e) {
    e.printStackTrace();
    javax.swing.JOptionPane.showMessageDialog(this, "Gagal menyimpan data: " + e.getMessage());
}
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnTambahProdukActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahProdukActionPerformed
                                                    
        try {
            String nama = javax.swing.JOptionPane.showInputDialog(this, "Masukkan Nama Produk Baru:");
            if (nama == null || nama.trim().isEmpty()) return;
            
            String hargaJualStr = javax.swing.JOptionPane.showInputDialog(this, "Masukkan Harga Jual:");
            if (hargaJualStr == null || hargaJualStr.trim().isEmpty()) return;
            
            String stokRakStr = javax.swing.JOptionPane.showInputDialog(this, "Masukkan Stok di Rak:");
            if (stokRakStr == null || stokRakStr.trim().isEmpty()) return;
            
            String totalStokStr = javax.swing.JOptionPane.showInputDialog(this, "Masukkan Total Stok Sistem:");
            if (totalStokStr == null || totalStokStr.trim().isEmpty()) return;
            
            String satuan = javax.swing.JOptionPane.showInputDialog(this, "Masukkan Satuan (Contoh: Kg / Buah):");
            if (satuan == null || satuan.trim().isEmpty()) satuan = "Kg";

            double hargaJual = Double.parseDouble(hargaJualStr);
            int stokRak = Integer.parseInt(stokRakStr);
            int totalStok = Integer.parseInt(totalStokStr);

            String barcode = "BRC-" + System.currentTimeMillis();

            java.sql.Connection conn = (java.sql.Connection) com.alambuahsegar.config.DatabaseConnection.getConnection();
            String sql = "INSERT INTO produk (barcode, nama_produk, harga_jual, stok_di_rak, total_stok_sistem, satuan) VALUES (?, ?, ?, ?, ?, ?)";
            java.sql.PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, barcode);
            pst.setString(2, nama);
            pst.setDouble(3, hargaJual);
            pst.setInt(4, stokRak);
            pst.setInt(5, totalStok);
            pst.setString(6, satuan);
            pst.execute();

            javax.swing.JOptionPane.showMessageDialog(this, "Produk baru berhasil ditambahkan!");
            tampilkanData();

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Format angka pada harga atau stok tidak valid!");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal menambah produk: " + e.getMessage());
        }                                    
            
    }//GEN-LAST:event_btnTambahProdukActionPerformed

